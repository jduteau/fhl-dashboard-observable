// One-time migration: turns the PW and EMAIL columns of an owners.csv into SQL that loads them into the D1 gm_accounts
// table, with the passwords hashed. Run it BEFORE removing those columns from owners.csv.
//
//   node worker/seed-accounts.mjs src/data/static/2026-27/owners.csv > worker/seed-accounts.sql
//   cd worker && npx wrangler d1 execute fhl-trades --remote --file=seed-accounts.sql
//
// The output contains emails and password hashes: seed-accounts.sql is gitignored, so don't commit it, and delete it
// after running it. Existing passwords are kept as they are; GMs change them on the My Account page.
import { readFileSync } from "node:fs";
import { csvParse } from "./lib.js";
import { hashPassword } from "./accounts.js";

const file = process.argv[2];
if (!file) { console.error("Usage: node worker/seed-accounts.mjs <owners.csv>"); process.exit(1); }

const rows = csvParse(readFileSync(file, "utf-8").replace(/^﻿/, ""));
if (!rows.length || !("PW" in rows[0])) { console.error(`${file} has no PW column: nothing to seed`); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const now = new Date().toISOString();
const out = ["-- Generated by seed-accounts.mjs: do not commit."];
for (const r of rows) {
  if (!r.ABBR || !r.PW) { console.error(`Skipping ${r.ABBR || "(blank)"}: no password`); continue; }
  const email = (r.EMAIL ?? "").trim();
  out.push(`INSERT INTO gm_accounts (team, email, pw, updated_at) VALUES (${q(r.ABBR)}, ${q(email)}, ${q(await hashPassword(r.PW))}, ${q(now)})` +
    ` ON CONFLICT(team) DO NOTHING;`); // never overwrite an account a GM has already changed
}
console.log(out.join("\n"));
console.error(`${out.length - 1} account(s) written`);
